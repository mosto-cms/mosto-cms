export const MESSAGES: Record<UiLanguage, Messages> = { en, it };
export const UI_LANGUAGES = ['en', 'it'] as const;
export type UiLanguage = (typeof UI_LANGUAGES)[number];
export const LANGUAGE_NAMES: Record<UiLanguage, string> = { en: 'English', it: 'Italiano' };

export const STORAGE_KEY = 'mosto-cms-admin-language';

/** The first browser language the admin speaks, else English. */
export function pickLanguage(preferred: readonly string[] | undefined, stored?: string | null): UiLanguage {
  if (stored && (UI_LANGUAGES as readonly string[]).includes(stored)) return stored as UiLanguage;
  for (const p of preferred ?? []) {
    const base = p.toLowerCase().split('-')[0];
    if ((UI_LANGUAGES as readonly string[]).includes(base as string)) return base as UiLanguage;
  }
  return 'en';
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: UiLanguage): Translate {
  const dict = MESSAGES[lang];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** "3 min ago" / "3 min fa", then a date. */
export function relativeTime(iso: string, lang: UiLanguage, now = Date.now()): string {
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) return '';
  const tr = translator(lang);
  const s = Math.max(0, Math.round((now - t) / 1000));
  if (s < 60) return tr('time.now');
  if (s < 3600) return tr('time.minutes', { n: Math.floor(s / 60) });
  if (s < 86400) return tr('time.hours', { n: Math.floor(s / 3600) });
  if (s < 2 * 86400) return tr('time.yesterday');
  return new Date(t).toLocaleDateString(lang === 'it' ? 'it-IT' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
}
